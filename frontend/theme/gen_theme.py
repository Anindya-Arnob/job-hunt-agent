import json, sys
tw = json.load(open(sys.argv[1]))
out_css, out_js = sys.argv[2], sys.argv[3]

def rgb(h):
    h = h.lstrip('#'); return f"{int(h[0:2],16)} {int(h[2:4],16)} {int(h[4:6],16)}"

SHADES = ["50","100","200","300","400","500","600","700","800","900","950"]
HUES = ["emerald","amber","rose","sky","violet","blue","fuchsia","indigo","red","green","orange","yellow","purple","cyan","pink","lime"]

dark, light = {}, {}
def put(d, name, color, a=1.0):
    d[name] = (color if " " in color else rgb(color), a)

# ---- semantic hues: light = Tailwind as is; dark = tinted glass + light text shades
for h in HUES:
    p = tw[h]
    for s in SHADES:
        put(light, f"{h}-{s}", p[s])
    m = {"50": (p["500"], .12), "100": (p["500"], .18), "200": (p["400"], .32), "300": (p["400"], .6),
         "400": (p["400"], 1), "500": (p["500"], 1), "600": (p["400"], 1), "700": (p["300"], 1),
         "800": (p["200"], 1), "900": (p["100"], 1), "950": (p["50"], 1)}
    for s, (c, a) in m.items():
        put(dark, f"{h}-{s}", c, a)

# ---- neutrals: inverted for dark (backgrounds become white veils, text shades become light)
sl = tw["slate"]
for s in SHADES:
    put(light, f"slate-{s}", sl[s])
for s, a in {"50": .045, "100": .075, "200": .11, "300": .2}.items():
    put(dark, f"slate-{s}", "255 255 255", a)
for s, c in {"400": "8B93A7", "500": "9BA4B5", "600": "B5BDCB", "700": "CFD5DF", "800": "E4E8EF", "900": "F3F5F9", "950": "FFFFFF"}.items():
    put(dark, f"slate-{s}", c)

# ---- brand (electric blue, from the reference) - used where the app said "teal"
brand_dark = {"50": ("47 124 255", .12), "100": ("47 124 255", .2), "200": ("96 165 250", .34), "300": ("96 165 250", .6),
              "400": ("96 165 250", 1), "500": ("47 124 255", 1), "DEFAULT": ("47 124 255", 1), "600": ("86 150 255", 1),
              "700": ("147 194 255", 1), "800": ("191 219 254", 1), "900": ("219 234 254", 1)}
brand_light = {"50": "EEF4FF", "100": "DCE8FF", "200": "BCD3FF", "300": "8DB4FF", "400": "5A92FF", "500": "2F6FED",
               "DEFAULT": "2F6FED", "600": "2459C9", "700": "1E4AA6", "800": "1C3F86", "900": "1A356B"}
for s, (c, a) in brand_dark.items():
    put(dark, f"teal-{s}", c, a)
for s, c in brand_light.items():
    put(light, f"teal-{s}", c)

# ---- navy = headings / strong ink
navy_dark = {"DEFAULT": ("241 244 250", 1), "50": ("255 255 255", .06), "100": ("255 255 255", .14),
             "700": ("255 255 255", .18), "800": ("241 244 250", 1), "900": ("0 0 0", 1)}
navy_light = {"DEFAULT": "1B2A4A", "50": "EEF1F6", "100": "D6DCE8", "700": "24365E", "800": "1B2A4A", "900": "121D33"}
for s, (c, a) in navy_dark.items():
    put(dark, f"navy-{s}", c, a)
for s, c in navy_light.items():
    put(light, f"navy-{s}", c)

# ---- glass surfaces
put(dark, "surface", "17 20 28", .5);  put(light, "surface", "255 255 255", .58)
put(dark, "surface2", "24 28 38", .9);  put(light, "surface2", "255 255 255", .88)
put(dark, "ink", "33 38 52", 1);         put(light, "ink", "27 42 74", 1)

def block(sel, d):
    lines = [f"{sel} {{"]
    for k, (c, a) in d.items():
        lines.append(f"  --c-{k}: {c}; --a-{k}: {a};")
    lines.append("}")
    return "\n".join(lines)

css = ("/* generated by gen_theme.py - colour tokens for the dark glass (default) and light frosted themes */\n"
       + block(":root", dark) + "\n" + block(':root[data-theme="light"]', light) + "\n")
open(out_css, "w").write(css)

# tailwind colour map
pal = {}
for k in dark:
    name, _, shade = k.partition("-")
    pal.setdefault(name, {})[shade or "DEFAULT"] = f"rgb(var(--c-{k}) / calc(var(--a-{k}) * <alpha-value>))"
pal["gray"] = pal["slate"]
open(out_js, "w").write("// generated by gen_theme.py\nexport default " + json.dumps(pal, indent=1) + "\n")
print(len(dark), "tokens")
